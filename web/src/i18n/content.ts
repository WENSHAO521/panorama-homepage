export function getContent(locale = 'en') {
  return (key: string, fallback?: string): string => copy[key]?.[locale as LocaleCode] ?? copy[key]?.en ?? fallback ?? key;
}

/** Return the public home/catalogue copy for search indexing in a locale. */
export function getContentStrings(locale = 'en'): string[] {
  return Object.values(copy)
    .map((translations) => translations[locale as LocaleCode] ?? translations.en)
    .filter((value): value is string => Boolean(value));
}

export function translateContent(locale: string, key: string, fallback?: string): string {
  return getContent(locale)(key, fallback);
}
